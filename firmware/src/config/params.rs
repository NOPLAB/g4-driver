//! モーター制御とハードウェアの設定パラメータ
//!
//! # モジュール構成
//! - `motor`: モーター物理特性（極対数など）
//! - `control`: 制御周期・タイミング
//! - `speed`: 速度制御（PIゲイン、フィルタ、加速度制限）
//! - `voltage`: 電圧関連（DCバス、最大/最小電圧）
//! - `hall`: Hallセンサ設定（角度オフセット）
//! - `advance_angle`: 進角制御
//! - `foc_stall`: FOC脱落検出
//! - `openloop`: オープンループ始動
//! - `pwm`: PWM設定
//! - `can`: CAN通信設定
//! - `dead_time_compensation`: デッドタイム補償
//! - `flux_weakening`: フラックス弱め制御

// =============================================================================
// モーター物理特性
// =============================================================================

/// モーター物理特性パラメータ
pub mod motor {
    /// 極対数（ポール数12 / 2 = 6）
    pub const DEFAULT_POLE_PAIRS: u8 = 6;
}

// =============================================================================
// 制御周期・タイミング
// =============================================================================

/// 制御周期パラメータ
pub mod control {
    /// 制御周期 [μs]（50kHz = 20μs）
    pub const DEFAULT_PERIOD_US: u64 = 20;
}

// =============================================================================
// 速度制御
// =============================================================================

/// 速度制御パラメータ（PIゲイン、フィルタ、加速度制限）
pub mod speed {
    /// 比例ゲイン Kp（発振抑制のため低めに設定）
    pub const DEFAULT_KP: f32 = 0.1;

    /// 積分ゲイン Ki（発振抑制のため低めに設定）
    pub const DEFAULT_KI: f32 = 0.02;

    /// 速度フィルタ係数 α（0.10: 応答性と安定性のバランス）
    pub const DEFAULT_FILTER_ALPHA: f32 = 0.10;

    /// 速度指令の最大加速度 [RPM/s]（200 RPM/sで緩やかな加速、PI制御の安定化）
    pub const MAX_ACCELERATION: f32 = 500.0;

    /// PI積分項リミット [V]（電圧飽和による脱調防止）
    pub const PI_INTEGRAL_LIMIT: f32 = 12.0;
}

// =============================================================================
// 電圧関連
// =============================================================================

/// 電圧関連パラメータ
pub mod voltage {
    /// DCバス電圧 [V]
    pub const DEFAULT_DC_BUS: f32 = 24.0;

    /// 最大出力電圧 [V]
    pub const DEFAULT_MAX: f32 = 24.0;

    /// 最小出力電圧 [V]（静止摩擦を克服するための最小電圧）
    pub const MIN: f32 = 2.0;

    /// 最小電圧適用のしきい値 [RPM]（速度誤差がこの値を超える場合に最小電圧を適用）
    pub const MIN_ERROR_THRESHOLD: f32 = 2.0;
}

// =============================================================================
// Hallセンサ
// =============================================================================

/// Hallセンサパラメータ
pub mod hall {
    /// 角度オフセット [度]
    /// ハードウェアに応じて調整。モーターが正しく回転しない場合は調整が必要。
    /// テーブル方式で基本電気角を設定済み。オフセットは微調整用。
    pub const DEFAULT_ANGLE_OFFSET_DEG: f32 = 0.0;
}

// =============================================================================
// 進角制御
// =============================================================================

/// 進角（Advance Angle）設定
/// 高速回転時にトルク効率を最大化するため、電気角に進角を加える
pub mod advance_angle {
    /// 基本進角 [度]（低速時から適用される固定進角）
    pub const BASE_ADVANCE_DEG: f32 = 10.0;

    /// 最大進角 [度]（高速時の最大進角）
    pub const MAX_ADVANCE_DEG: f32 = 30.0;

    /// 進角が最大になる速度 [RPM]
    pub const MAX_SPEED_FOR_ADVANCE: f32 = 3000.0;

    /// 進角を適用し始める速度 [RPM]（これ以下では基本進角のみ）
    pub const MIN_SPEED_FOR_ADVANCE: f32 = 100.0;
}

// =============================================================================
// FOC脱落検出
// =============================================================================

/// FOC脱落検出パラメータ
pub mod foc_stall {
    /// 脱落判定の速度閾値 [RPM]
    /// 実測速度がこの値以下になると脱落カウンタが増加
    pub const SPEED_THRESHOLD: f32 = 50.0;

    /// 脱落判定の連続回数閾値
    /// 50kHz制御で2500回 = 50ms以上連続して低速ならOpenLoopに戻る
    /// 早期検出により脱調からの回復を迅速化
    pub const COUNT_THRESHOLD: u32 = 2500;
}

// =============================================================================
// オープンループ始動
// =============================================================================

/// オープンループ始動パラメータ（6ステップ駆動）
pub mod openloop {
    /// 初期回転数 [RPM]（起動用：50RPMから開始）
    pub const DEFAULT_INITIAL_RPM: f32 = 50.0;

    /// FOC切替回転数 [RPM]
    pub const DEFAULT_TARGET_RPM: f32 = 100.0;

    /// 加速度 [RPM/s]
    pub const DEFAULT_ACCELERATION: f32 = 200.0;

    /// デューティ比 (0-100)（Hall ベース駆動用：10%）
    pub const DEFAULT_DUTY_RATIO: u16 = 10;

    /// SVPWMベース強制転流フェーズの実行回数（50000 = 1秒 @ 50kHz）
    pub const FORCED_COMMUTATION_CYCLES: u32 = 50000;

    /// FOC切り替えまでの最小実行回数（50000 = 1秒 @ 50kHz）
    pub const MIN_CYCLES_BEFORE_FOC: u32 = 50000;

    /// FOC切り替えに必要な最小速度 [RPM]
    pub const MIN_SPEED_FOR_FOC: f32 = 100.0;
}

// =============================================================================
// PWM設定
// =============================================================================

/// PWM設定パラメータ
pub mod pwm {
    use embassy_stm32::time::Hertz;

    /// PWM周波数（50kHz）
    pub const DEFAULT_FREQUENCY: Hertz = Hertz(50_000);

    /// デッドタイム
    pub const DEFAULT_DEAD_TIME: u16 = 2;
}

// =============================================================================
// CAN通信
// =============================================================================

/// CAN通信設定パラメータ
pub mod can {
    /// ビットレート（250kbps）
    pub const DEFAULT_BITRATE: u32 = 250_000;
}

// =============================================================================
// デッドタイム補償
// =============================================================================

/// デッドタイム補償パラメータ
pub mod dead_time_compensation {
    /// 補償有効/無効（デフォルト: 無効）
    pub const ENABLED: bool = false;

    /// 補償対象のデッドタイム [ns]
    pub const DEAD_TIME_NS: f32 = 100.0;
}

// =============================================================================
// フラックス弱め制御
// =============================================================================

/// フラックス弱め制御パラメータ
pub mod flux_weakening {
    /// 制御有効/無効（デフォルト: 無効）
    pub const ENABLED: bool = false;

    /// 弱め制御開始速度 [RPM]
    pub const MIN_SPEED: f32 = 2000.0;

    /// 最大弱め速度 [RPM]
    pub const MAX_SPEED: f32 = 4000.0;

    /// 最大弱め率 (0.0-1.0)
    pub const MAX_WEAKENING_RATIO: f32 = 0.5;

    /// Vdレート制限 [V/s]
    pub const VD_RATE_LIMIT: f32 = 100.0;
}
